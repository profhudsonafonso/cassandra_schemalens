"""SchemaLens IoT Benchmark -> Cassandra PHASE A1 bridge.

No live DB, no imported TSBS results, no performance-dependent activation.
Native IoT Benchmark generated CSV reader matches CSVDataWriter / CSVSchemaWriter.
The restricted pilot only accepts DOUBLE sensors; other types fail fast.
"""
from __future__ import annotations
import csv
import hashlib
import json
import math
import re
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

SENSOR_TYPES = ['BOOLEAN','INT32','INT64','FLOAT','DOUBLE','TEXT','STRING','BLOB','TIMESTAMP','DATE','OBJECT']
ALLOWED = frozenset('TS'+str(i) for i in range(9))
ID = re.compile(r'^[a-zA-Z_][a-zA-Z0-9_]*$')
DEVICE = re.compile(r'^[a-zA-Z0-9_][a-zA-Z0-9_.:-]*$')
DAY_MS = 86_400_000


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def json_write(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False)+'\n',encoding='utf-8')


def read_properties(path: Path) -> dict[str,str]:
    result={}
    for lineno,line in enumerate(path.read_text(encoding='utf-8').splitlines(),1):
        s=line.strip()
        if not s or s.startswith(('#','!')):
            continue
        if '=' not in s: raise ValueError(f'Invalid properties line {lineno}: {s}')
        k,v=map(str.strip,s.split('=',1))
        if k in result: raise ValueError(f'Duplicate property: {k}')
        result[k]=v
    return result


def read_native(data_dir:Path, max_rows:int=100_000) -> dict:
    """Read IoT Benchmark CSV generated by generateDataMode.

    The official writer emits a per-device directory with BigBatch_*.csv;
    'Sensor,<col>,...' headers can repeat within a file (per batch).
    schema.txt has 'device sensor ordinal'. Null cells are empty.
    Duplicate (device,sensor,time) values are rejected in this initial pilot
    rather than guessing INSERT conflict resolution.
    """
    if not isinstance(max_rows,int) or max_rows<1: raise ValueError('max_rows must be positive')
    schema_path=data_dir/'schema.txt'
    if not schema_path.is_file(): raise FileNotFoundError(schema_path)
    schema:dict[str,dict[str,str]]={}
    for no,line in enumerate(schema_path.read_text(encoding='utf-8').splitlines(),1):
        if not line.strip(): continue
        parts=line.split()
        if len(parts)!=3: raise ValueError(f'schema.txt line {no}: expected device sensor type_ordinal')
        device,sensor,ordinal=parts
        if not DEVICE.fullmatch(device) or device in {'.','..'} or '..' in device or not ID.fullmatch(sensor):
            raise ValueError(f'Unsafe device/sensor name: {device}/{sensor}')
        n=int(ordinal)
        if n<0 or n>=len(SENSOR_TYPES): raise ValueError('Invalid sensor type ordinal')
        dtype=SENSOR_TYPES[n]
        if dtype != 'DOUBLE':
            raise ValueError(f'{device}/{sensor}: pilot only supports DOUBLE, got {dtype}')
        if sensor in schema.setdefault(device,{}):
            raise ValueError(f'Duplicate sensor schema: {device}/{sensor}')
        schema[device][sensor]=dtype
    if not schema: raise ValueError('Empty schema')
    raw_files=[]
    by_key:dict[tuple[str,str,int],float]={}
    batch_count=0
    for device in sorted(schema):
        files=sorted((data_dir/device).glob('BigBatch_*.csv'))
        if not files: raise FileNotFoundError(f'No BigBatch_*.csv for {device}')
        for path in files:
            raw_files.append(path)
            header=None
            with path.open(encoding='utf-8',newline='') as stream:
                for no,parts in enumerate(csv.reader(stream),1):
                    if not parts: continue
                    if parts[0]=='Sensor':
                        header=parts[1:]
                        batch_count+=1
                        if not header or len(header)!=len(set(header)) or not set(header)<=set(schema[device]):
                            raise ValueError(f'Invalid sensor header {path}:{no}')
                        continue
                    if header is None: raise ValueError(f'Missing Sensor header: {path}:{no}')
                    if len(parts)!=len(header)+1: raise ValueError(f'Column count mismatch {path}:{no}')
                    try:
                        timestamp=int(parts[0])
                    except ValueError as exc: raise ValueError(f'Invalid timestamp {path}:{no}') from exc
                    if not -(2**63)<=timestamp<2**63:
                        raise ValueError('Timestamp exceeds signed 64-bit integer')
                    # Explicit bounded millisecond pilot. Prevent silently treating
                    # a generated nanosecond series as millisecond dates.
                    if not -2208988800000 <= timestamp <= 10413792000000:
                        raise ValueError('Timestamp outside pilot ms range (1900-2300); check TIMESTAMP_PRECISION')
                    for sensor,value in zip(header,parts[1:]):
                        if value=='': continue   # official NULL_RATIO sparse output
                        try: v=float(value)
                        except ValueError as exc: raise ValueError(f'Non-double reading: {path}:{no}') from exc
                        if not math.isfinite(v): raise ValueError('Non-finite reading')
                        key=(device,sensor,timestamp)
                        if key in by_key:
                            if by_key[key]!=v: raise ValueError(f'Conflicting duplicate reading: {key}')
                            continue
                        by_key[key]=v
                        if len(by_key)>max_rows: raise ValueError('max_rows exceeded; explicitly increase the limit')
    if not by_key: raise ValueError('No observed readings')
    records=[{'device_id':d,'sensor_name':s,'timestamp':t,'value_double':v}
             for (d,s,t),v in sorted(by_key.items())]
    sensor_order=sorted(set.intersection(*(set(x) for x in schema.values())))
    if any(set(s)!=set(sensor_order) for s in schema.values()):
        raise ValueError('Pilot expects same sensor set on every device (TS2 wide physical candidate)')
    return {'records':records,'schema':schema,'devices':sorted(schema),'sensors':sensor_order,
            'count':len(records),'batch_headers':batch_count,
            'min_timestamp':min(x['timestamp'] for x in records),
            'max_timestamp':max(x['timestamp'] for x in records),
            'files_sha256':{str(p.relative_to(data_dir)):digest(p) for p in [schema_path,*raw_files]},
            'source_format':'iot_benchmark_generateDataMode_native_csv',
            'timestamp_precision':'ms (must be confirmed against info.txt/config)',
            'null_handling':'skip empty sensor cell', 'duplicate_handling':'reject conflicting duplicate'}


def bucket_start_ms(t:int,days:int=1) -> int:
    return (t//(DAY_MS*days))*(DAY_MS*days)


def day_iso_ms(t:int) -> str:
    return datetime.fromtimestamp(t/1000,timezone.utc).date().isoformat()


def make_queries(data:dict, scenario:dict, operations:list[dict]) -> list[dict]:
    """Illustrative deterministic parameter binding; NOT native QUERY_SEED replay."""
    if scenario['dialect']!='table': raise ValueError('Q12 requires table dialect in original benchmark')
    sensors=data['sensors']
    if scenario['query_sensor_num']>len(sensors):
        raise ValueError('QUERY_SENSOR_NUM exceeds dataset sensors')
    if len(data['devices'])<2: raise ValueError('Q12 demo needs two distinct devices')
    start=data['min_timestamp']; end=data['max_timestamp']+1
    # User-provided scenario fixed QUERY_AGGREGATE_FUN and groupby resolution.
    func=scenario['query_aggregate_fun'].lower()
    if func not in {'count','sum','max','min','avg'}:
        raise ValueError('Unsupported pilot aggregation function')
    g=int(scenario['group_by_time_unit_ms'])
    if g<=0: raise ValueError('Invalid GROUP_BY_TIME_UNIT')
    ids=[x['id'] for x in operations]
    if ids!=[f'Q{i}' for i in range(1,13)]: raise ValueError('Expected operations Q1-Q12 in order')
    result=[]
    for op in operations:
        qid=op['id']
        result.append({'query_id':qid,'name':op['name'],
                       'devices':data['devices'][:2] if qid=='Q12' else data['devices'][:scenario['query_device_num']],
                       'sensors':sensors[:scenario['query_sensor_num']],
                       'start_ms':start, 'end_ms_exclusive':end,
                       'point_ms':start,
                       'aggregation':func if op['aggregate'] else None,
                       'value_lower':scenario['query_lower_value'] if qid in {'Q3','Q5','Q6','Q10'} else None,
                       'group_by_ms':g if qid in {'Q7','Q11'} else None,
                       'set_op':'union' if qid=='Q12' else None,
                       'parameter_origin':'deterministic illustrative pilot; NOT official QUERY_SEED sequence',
                       'correctness_status':'reference-evaluable, not live Cassandra-validated'})
    return result


def _result(records: list[dict], q:dict):
    qid=q['query_id']; devices=set(q['devices']); sensors=set(q['sensors'])
    start,end=q['start_ms'],q['end_ms_exclusive']
    subset=[x for x in records if x['device_id'] in devices and x['sensor_name'] in sensors]
    if qid=='Q1': subset=[x for x in subset if x['timestamp']==q['point_ms']]
    if qid not in {'Q1','Q5','Q8'}:
        subset=[x for x in subset if start<=x['timestamp']<end]
    if q['value_lower'] is not None:
        # Official table SQL appends: AND s0 > threshold AND s1 > threshold.
        # This is a row-level predicate on one (device,time) containing *all*
        # selected sensors, not a separate filter on each metric point.
        by_row={}
        for x in subset:
            by_row.setdefault((x['device_id'],x['timestamp']),{})[x['sensor_name']]=x['value_double']
        good={key for key,values in by_row.items()
              if all(values.get(sensor,float('-inf'))>q['value_lower'] for sensor in sensors)}
        subset=[x for x in subset if (x['device_id'],x['timestamp']) in good]
    subset.sort(key=lambda x:(x['device_id'],x['sensor_name'],x['timestamp']))
    if qid in {'Q1','Q2','Q3','Q9','Q10'}:
        if qid in {'Q9','Q10'}:
            subset.sort(key=lambda x:(x['device_id'],x['sensor_name'],-x['timestamp']))
        return subset
    if qid=='Q8':
        latest={}
        for x in subset:
            k=(x['device_id'],x['sensor_name'])
            if k not in latest or x['timestamp']>latest[k]['timestamp']:latest[k]=x
        return [latest[k] for k in sorted(latest)]
    if qid=='Q12':
        # IoTDB table-mode SQL projects selected sensor FIELD columns, not
        # timestamp/device_id under normal query mode. Reconstruct those tuples
        # from multi-metric rows *before* SQL set operations. DISTINCT semantics
        # apply to projected tuples; device/time are not part of row identity.
        children=q.get('set_children')
        if children is None:
            if len(q['devices'])<2:raise ValueError('Q12 requires at least two child operands')
            children=[{'devices':[d], 'sensors':q['sensors'],
                       'start_ms':start, 'end_ms_exclusive':end} for d in q['devices'][:2]]
        if len(children)<2:raise ValueError('Q12 requires two or more child operands')
        sets=[]
        for ch in children:
            by_dt={}
            for x in records:
                if x['device_id'] in ch['devices'] and x['sensor_name'] in ch['sensors'] and \
                    ch['start_ms']<=x['timestamp']<ch['end_ms_exclusive']:
                    by_dt.setdefault((x['device_id'],x['timestamp']),{})[x['sensor_name']]=x['value_double']
            sets.append({tuple(values.get(s) for s in ch['sensors']) for values in by_dt.values()})
        op=q['set_op'].lower()
        if op=='union': answer=set.union(*sets)
        elif op=='intersect': answer=set.intersection(*sets)
        elif op=='except':
            answer=sets[0].copy()
            for other in sets[1:]:answer-=other
        else:raise ValueError('Unsupported SQL set operation: '+op)
        return sorted(answer,key=repr)
    def agg(rows):
        values=[r['value_double'] for r in rows]
        if not values:return None
        return {'count':len(values),'sum':sum(values),'max':max(values),
                'min':min(values),'avg':sum(values)/len(values)}[q['aggregation']]
    if qid in {'Q4','Q5','Q6'}:
        return [{'device_id':d,'sensor_name':s,'aggregate':agg([x for x in subset if (x['device_id'],x['sensor_name'])==(d,s)])}
                for d in q['devices'] for s in q['sensors']]
    if qid in {'Q7','Q11'}:
        # Native IoTDB date_bin() in table mode uses epoch-aligned windows;
        # a query may begin within a window, so TS5 needs boundary guards.
        groups={}
        for x in subset:
            w=(x['timestamp']//q['group_by_ms'])*q['group_by_ms']
            groups.setdefault((x['device_id'],x['sensor_name'],w),[]).append(x)
        rows=[{'device_id':d,'sensor_name':s,'window_start_ms':w,'aggregate':agg(v)}
              for (d,s,w),v in groups.items()]
        return sorted(rows,key=lambda x:(x['device_id'],x['sensor_name'],-x['window_start_ms'] if qid=='Q11' else x['window_start_ms']))
    raise ValueError('Unsupported operation: '+qid)


def make_cassandra_specs(sensors:list[str], scenario:dict) -> list[dict]:
    """TS-only DDL blueprints. Not silently relabelled TSBS Stage4 objects."""
    cols=[]
    for s in sensors:
        if not ID.fullmatch(s): raise ValueError('Unsafe sensor name')
        cols.append('m_'+s)
    cql=[
      ('TS0','ts0_iot_raw',"CREATE TABLE IF NOT EXISTS ts0_iot_raw (device_id text, sensor_name text, timestamp_ms bigint, value_double double, PRIMARY KEY ((device_id,sensor_name),timestamp_ms)) WITH CLUSTERING ORDER BY (timestamp_ms DESC);",'always baseline; unbucketed growth risk'),
      ('TS1','ts1_iot_bucket',"CREATE TABLE IF NOT EXISTS ts1_iot_bucket (device_id text, sensor_name text, bucket_day date, timestamp_ms bigint, value_double double, PRIMARY KEY ((device_id,sensor_name,bucket_day),timestamp_ms)) WITH CLUSTERING ORDER BY (timestamp_ms DESC);",'enumerate all UTC days including boundary days'),
      ('TS2','ts2_iot_wide',f"CREATE TABLE IF NOT EXISTS ts2_iot_wide (device_id text, bucket_day date, timestamp_ms bigint, {', '.join(c+' double' for c in cols)}, PRIMARY KEY ((device_id,bucket_day),timestamp_ms)) WITH CLUSTERING ORDER BY (timestamp_ms DESC);",'row per device+timestamp; sparse/null handling required'),
      ('TS4','ts4_iot_latest',"CREATE TABLE IF NOT EXISTS ts4_iot_latest (device_id text, sensor_name text, latest_timestamp_ms bigint, value_double double, PRIMARY KEY ((device_id,sensor_name)));",'native Q8 is global last/last_by, with missing-value and update semantics requiring verification'),
      ('TS5','ts5_iot_rollup',"CREATE TABLE IF NOT EXISTS ts5_iot_rollup (device_id text, sensor_name text, bucket_day date, window_start_ms bigint, value_sum double, sample_count bigint, minimum double, maximum double, PRIMARY KEY ((device_id,sensor_name,bucket_day),window_start_ms)) WITH CLUSTERING ORDER BY (window_start_ms DESC);",'only aligned groups; full correct mutation plan not implemented'),
    ]
    return [{'family':family,'candidate_id':table,'table_name':table,'ddl':ddl,
             'status':'DDL_BLUEPRINT_ONLY_NOT_BENCHMARK_READY', 'guard':guard,
             'C0_C9_used':False} for family,table,ddl,guard in cql]


def coverage_decisions(activation_rows:list[dict],queries:list[dict],specs:list[dict]) -> list[dict]:
    by_id={x['query_id']:x for x in activation_rows}
    by_f={x['family']:x['candidate_id'] for x in specs}
    result=[]
    for q in queries:
        qid=q['query_id']
        for family in by_id[qid]['ts_families']:
            if family not in ALLOWED: raise ValueError('Non TS-only activation')
            reason={
              'TS0':'raw reference-query interpretation; physical reader not implemented',
              'TS1':'multi-bucket enumeration + client filtering needed; reader not implemented',
              'TS2':'wide metric alignment and client filtering needed; reader not implemented',
              'TS4':'only newest global snapshot; Q8 official table SQL has no temporal predicate; safe update protocol required',
              'TS5':'time groups must align with pre-aggregation; updates must maintain aggregates exactly',
              'TS3':'alternate access physical schema not implemented',
              'TS6':'dimension rollup physical schema not implemented',
              'TS7':'series discovery index not implemented',
              'TS8':'segment model not implemented',
            }[family]
            guard=None
            if family=='TS5':
                guard={'query_start_aligned':q['start_ms']%q['group_by_ms']==0,
                       'full_window_covered':(q['end_ms_exclusive']-q['start_ms'])%q['group_by_ms']==0,
                       'aggregate_supported':q['aggregation'] in {'count','sum','avg','min','max'}}
            result.append({'query_id':qid,'family':family,
                           'candidate_id':by_f.get(family),
                           'provenance':'activator TS-only; no benchmark inputs',
                           'coverage':'NOT_VALIDATED',
                           'gates':guard,'explanation':reason})
    return result
